import { test, expect } from '../models/fixture-website'
import { MqttMessageLogModel } from '../models/mqtt'

test.use({ colorScheme: 'light' })
// reset storage state
test.use({ storageState: { cookies: [], origins: [] } });

test.describe('MQTT message log in the demo dashboard', () => {
    const serviceLog = '/mqtt/log/Smart%20Home%20MQTT%20API'
    const templateTopic = 'sensors/{sensorId}/data'
    let dashboardPath: string
    let isDemo: boolean

    test.beforeEach(({ baseURL }) => {
        isDemo = baseURL !== 'http://localhost:8080'
        dashboardPath = isDemo ? '/dashboard-demo' : '/dashboard'
    })

    test('log of one cluster shows the recorded messages', async ({ page }) => {
        await page.goto(`${dashboardPath}${serviceLog}`)

        const log = new MqttMessageLogModel(page)
        await expect(log.rows).toHaveCount(1)
        await expect(log.rows.first()).toContainText('sensors/12345/data')
    })

    test('log of all clusters shows the recorded messages', async ({ page }) => {
        await page.goto(`${dashboardPath}/mqtt/log`)

        const log = new MqttMessageLogModel(page)
        await expect(log.rows.first()).toBeVisible()
        await expect(log.addFilter).toBeVisible()
    })

    test('a message opens in the panel', async ({ page }) => {
        await page.goto(`${dashboardPath}${serviceLog}`)

        const log = new MqttMessageLogModel(page)
        await log.time(log.rows.first()).click()

        await expect(log.panel.element).toBeVisible()
        await expect(log.panel.element.getByLabel('Topic', { exact: true })).toHaveText('sensors/12345/data')
        await expect(log.panel.openAsTab).toBeVisible()
        await expect(page).toHaveURL(/message=/)
    })

    test('an unknown message id shows that the message is not found', async ({ page }) => {
        await page.goto(`${dashboardPath}${serviceLog}?message=00000000-0000-4000-8000-000000000000`)

        const log = new MqttMessageLogModel(page)
        await expect(log.panel.element.getByText('MQTT Message not found')).toBeVisible()
    })

    test('the Topic chip with the name of the template matches its instances', async ({ page }) => {
        await page.goto(`${dashboardPath}${serviceLog}`)
        const log = new MqttMessageLogModel(page)
        await expect(log.rows).toHaveCount(1)

        const popover = await log.openAddFilter('Topic')
        await popover.getByRole('combobox', { name: 'Topic' }).fill(templateTopic)
        await page.keyboard.press('Escape')

        await expect(log.chips).toHaveText([`Topic: ${templateTopic}`])
        await expect(log.rows).toHaveCount(1)

        await log.chip(`Topic: ${templateTopic}`).edit.click()
        await page.getByRole('dialog', { name: 'Topic', exact: true }).getByRole('combobox', { name: 'Topic' }).fill('no-such-topic')
        await page.keyboard.press('Escape')

        await expect(log.rows).toHaveCount(0)
    })

    test('the Client chip filters the log', async ({ page }) => {
        await page.goto(`${dashboardPath}${serviceLog}`)
        const log = new MqttMessageLogModel(page)
        await expect(log.rows).toHaveCount(1)
        // the id of the recorded client is generated by the MQTT library, so read it from the message
        await log.time(log.rows.first()).click()
        await log.panel.tab('Details').click()
        const clientId = (await log.panel.content.getByLabel('Client', { exact: true }).innerText()).trim()
        await log.panel.closeButton.click()

        const popover = await log.openAddFilter('Client')
        await popover.getByRole('textbox', { name: 'Client' }).fill(clientId)
        await page.keyboard.press('Escape')

        await expect(log.chips).toHaveText([`Client: ${clientId}`])
        await expect(log.rows).toHaveCount(1)

        await log.chip(`Client: ${clientId}`).edit.click()
        await page.getByRole('dialog', { name: 'Client', exact: true }).getByRole('textbox', { name: 'Client' }).fill('someone-else')
        await page.keyboard.press('Escape')

        await expect(log.rows).toHaveCount(0)
    })

    test('Pause is not offered', async ({ page }) => {
        test.skip(!isDemo, 'the live dashboard offers Pause')
        await page.goto(`${dashboardPath}${serviceLog}`)

        const log = new MqttMessageLogModel(page)
        await expect(log.rows).toHaveCount(1)
        await expect(log.pause).toHaveCount(0)
    })
})
